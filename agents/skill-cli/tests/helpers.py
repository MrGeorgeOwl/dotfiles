from __future__ import annotations

import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / "skill-cli"
HOME_VARS = ("AGENTS_HOME", "CODEX_HOME", "CLAUDE_HOME", "GROK_HOME", "PI_HOME")
XDG_VARS = ("XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_CACHE_HOME")
ENV_DROP = HOME_VARS + XDG_VARS + ("SKILL_CLI_ENTRYPOINT",)
SKILL_HOMES = (".agents", ".codex", ".claude", ".grok")


def make_git_skill_repo(
    root: Path,
    name: str = "tool",
    body: str = "from-git\n",
    subdir: str | None = None,
) -> tuple[str, str, str]:
    """Create a local git repo with a skill; return (url, pin, path)."""
    src = root / f"ext-{name}"
    if src.exists():
        shutil.rmtree(src)
    skill_rel = Path(subdir) if subdir else Path(name)
    skill_dir = src / skill_rel
    skill_dir.mkdir(parents=True)
    (skill_dir / "SKILL.md").write_text(
        f"---\nname: {name}\ndescription: External {name}\n---\n{body}"
    )
    subprocess.run(["git", "init"], cwd=src, check=True, capture_output=True)
    subprocess.run(
        ["git", "config", "user.email", "t@example.com"],
        cwd=src, check=True, capture_output=True,
    )
    subprocess.run(
        ["git", "config", "user.name", "t"],
        cwd=src, check=True, capture_output=True,
    )
    subprocess.run(["git", "add", "-A"], cwd=src, check=True, capture_output=True)
    subprocess.run(["git", "commit", "-m", "init"], cwd=src, check=True, capture_output=True)
    pin = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=src, check=True, capture_output=True, text=True,
    ).stdout.strip()
    return src.resolve().as_uri(), pin, str(skill_rel)


class SkillCliFixture(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.home = self.root / "home"
        self.home.mkdir()
        self.entry = self.root / "repo/agents"
        self.script = self.entry / "skill-cli/skill-cli"
        self.script.parent.mkdir(parents=True)
        shutil.copy2(SCRIPT, self.script)
        self.env = {k: v for k, v in os.environ.items() if k not in ENV_DROP}
        self.env["HOME"] = str(self.home)
        self.env["SKILL_CLI_ENTRYPOINT"] = str(self.entry)
        cache = self.root / "cache"
        cache.mkdir()
        self.env["UV_CACHE_DIR"] = str(cache / "uv")
        self.env["XDG_CACHE_HOME"] = str(cache)
        self.env["XDG_DATA_HOME"] = str(self.root / "data")
        self.env["XDG_CONFIG_HOME"] = str(self.root / "cfg")

    def add_skill(self, name: str, description: str = "Test skill") -> Path:
        path = self.entry / "skills" / name / "SKILL.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(f"---\nname: {name}\ndescription: {description}\n---\nbody\n")
        return path

    def write_registry(self, *entries: str) -> None:
        header = (
            "# Shared agent skills. Generated by `skill-cli registry`.\n"
            "# Edit status, purpose, source, agents.\n"
            "# name and description come from SKILL.md (local) or cache (external).\n"
            "# External skills use source.url + source.pin (+ optional source.path);\n"
            "# they are NOT stored under agents/skills/ — sync fetches them into cache.\n"
        )
        (self.entry / "skills.yaml").write_text(header + "".join(entries))

    def registry_entry(
        self,
        name: str,
        description: str = "Test skill",
        status: str = "active",
        purpose: str = "",
        agents: str | None = None,
        source: dict | None = None,
    ) -> str:
        text = (
            f'- name: "{name}"\n'
            f'  description: "{description}"\n'
            f'  status: "{status}"\n'
            f'  purpose: "{purpose}"\n'
        )
        if agents is not None:
            text += f"  agents: {agents}\n"
        if source is not None:
            text += "  source:\n"
            text += f'    url: "{source["url"]}"\n'
            text += f'    pin: "{source["pin"]}"\n'
            if source.get("path"):
                text += f'    path: "{source["path"]}"\n'
        return text

    def run_cli(self, *args, check=True):
        return subprocess.run(
            ["uv", "run", "--script", str(self.script), *args],
            env=self.env, check=check, capture_output=True, text=True,
        )
