"""skills.yaml read/write and validation."""

from __future__ import annotations

import json
import re
from pathlib import Path

from skill_cli.console import PROG
from skill_cli.fetch import find_cached_skill_dir
from skill_cli.paths import SYNCED, Paths
from skill_cli.skills import (
    NAME_RE,
    Source,
    find_problems,
    list_repo_skills,
    read_frontmatter,
)

STATUSES = ("active", "experimental", "deprecated")


def format_yaml_value(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def read_registry(paths: Paths) -> dict[str, dict]:
    """Parse the list-of-mappings YAML that render_registry writes.

    Supports one level of nesting for `source:` (url / pin / path).
    """
    entries: dict[str, dict] = {}
    current: dict | None = None
    nest: dict | None = None
    if not paths.registry.is_file():
        return entries
    for line in paths.registry.read_text().splitlines():
        nest_match = re.match(r"^    (\w+):(?: (.*))?$", line)
        if nest_match and nest is not None:
            key, raw = nest_match.group(1), nest_match.group(2)
            if raw is None:
                continue
            try:
                value = json.loads(raw)
            except ValueError:
                value = raw.strip()
            nest[key] = value
            continue
        match = re.match(r"^(- |  )(\w+):(?: (.*))?$", line)
        if not match:
            continue
        lead, key, raw = match.groups()
        nest = None
        if raw is None:
            if current is None:
                continue
            nest = {}
            current[key] = nest
            continue
        try:
            value = json.loads(raw)
        except ValueError:
            value = raw.strip()
        if lead == "- " and key == "name":
            current = entries.setdefault(value, {})
        elif current is not None:
            current[key] = value
    return entries


def render_entry(
    name: str,
    description: str,
    status: str,
    purpose: str,
    agents: object = None,
    source: dict | None = None,
) -> list[str]:
    lines = [
        f"- name: {format_yaml_value(name)}",
        f"  description: {format_yaml_value(description)}",
        f"  status: {format_yaml_value(status)}",
        f"  purpose: {format_yaml_value(purpose)}",
    ]
    if source is not None:
        lines += [
            "  source:",
            f"    url: {format_yaml_value(source.get('url') or '')}",
            f"    pin: {format_yaml_value(source.get('pin') or '')}",
        ]
        path = source.get("path") or ""
        if path:
            lines.append(f"    path: {format_yaml_value(path)}")
    if agents:
        lines.append(f"  agents: {format_yaml_value(agents)}")
    return lines


def render_registry(paths: Paths, old: dict[str, dict] | None = None) -> str:
    old = old if old is not None else read_registry(paths)
    out = [
        "# Shared agent skills. Generated by `skill-cli registry`.",
        "# Edit status, purpose, source, agents.",
        "# name and description come from SKILL.md (local) or cache (external).",
        "# External skills use source.url + source.pin (+ optional source.path);",
        "# they are NOT stored under agents/skills/ — sync fetches them into cache.",
    ]
    emitted: set[str] = set()
    for skill in list_repo_skills(paths):
        if not (skill / "SKILL.md").is_file():
            continue
        name = skill.name
        human = old.get(name, {})
        desc = read_frontmatter(skill / "SKILL.md").get("description", "")
        out += render_entry(
            name,
            desc,
            human.get("status") or "active",
            human.get("purpose") or "",
            human.get("agents"),
        )
        emitted.add(name)

    for name, fields in sorted(old.items()):
        if name in emitted:
            continue
        src = fields.get("source")
        if not isinstance(src, dict):
            continue
        desc = fields.get("description") or ""
        cached = find_cached_skill_dir(name, src)
        if cached is not None:
            desc = read_frontmatter(cached / "SKILL.md").get("description", desc)
        out += render_entry(
            name,
            desc,
            fields.get("status") or "experimental",
            fields.get("purpose") or "",
            fields.get("agents"),
            source=src,
        )
        emitted.add(name)
    return "\n".join(out) + "\n"


def find_registry_errors(paths: Paths) -> list[str]:
    errors: list[str] = []
    source_issue = False
    registry = read_registry(paths)
    repo = {s.name: s for s in list_repo_skills(paths)}
    for name, skill in repo.items():
        errors += [f"{name}: {p}" for p in find_problems(skill)]
        if Source.from_fields(registry.get(name, {})):
            errors.append(
                f"{name}: external skill must not have {paths.skills_dir.name}/{name}/; "
                "remove the folder (sync fetches into cache)"
            )
    for name, fields in registry.items():
        if not NAME_RE.match(name) or len(name) > 64:
            errors.append(f"{name}: name must be lowercase-hyphen, <= 64 chars")
        if fields.get("status") not in STATUSES:
            errors.append(f"{name}: status must be one of {', '.join(STATUSES)}")
        agents = fields.get("agents")
        if agents is not None and agents != "":
            if not isinstance(agents, list):
                errors.append(
                    f"{name}: agents must be a YAML list, got {type(agents).__name__}"
                )
            else:
                bad = [str(p) for p in agents if str(p) not in SYNCED]
                if bad:
                    errors.append(
                        f"{name}: unknown agents {bad}; expected subset of {list(SYNCED)}"
                    )
        raw = fields.get("source")
        if raw is None or raw == "":
            if name not in repo:
                errors.append(
                    f"{name}: listed in registry but no {paths.skills_dir.name}/{name}/"
                )
            continue
        if not isinstance(raw, dict):
            errors.append(f"{name}: source must be a mapping with url and pin")
            source_issue = True
            continue
        src = Source.from_fields(fields)
        if src is None:
            errors.append(f"{name}: source.url missing")
            source_issue = True
            continue
        problems = src.find_problems()
        if problems:
            source_issue = True
            errors += [f"{name}: {p}" for p in problems]
    for name, skill in repo.items():
        if name not in registry and (skill / "SKILL.md").is_file():
            errors.append(f"{name}: missing from {paths.registry.name}; run {PROG} registry")
    stale = (
        not paths.registry.is_file()
        or paths.registry.read_text() != render_registry(paths, registry)
    )
    if stale and not source_issue:
        errors.append(f"{paths.registry.name} is out of date; run {PROG} registry")
    return errors


def write_registry(paths: Paths, old: dict[str, dict] | None = None) -> None:
    paths.registry.write_text(render_registry(paths, old))
